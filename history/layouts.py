C={"mb":"#4a7fb5","cpu":"#c0504d","r420":"#e08a3c","gpu":"#6aa84f","r360":"#a4c86a","psu":"#8e7cc3","base":"#333333"}
def box(ax,x,y,w,h,c,t,ang=0,tc="k"):
    r=Rectangle((x,y),w,h,fc=c,ec="k",lw=1)
    r.set_transform(T.Affine2D().rotate_deg_around(x,y,ang)+ax.transData); ax.add_patch(r)
    a=math.radians(ang); cx=x+w/2*math.cos(a)-h/2*math.sin(a); cy=y+w/2*math.sin(a)+h/2*math.cos(a)
    rot=ang+(90 if h>w*1.5 else 0)
    ax.text(cx,cy,t,ha="center",va="center",fontsize=8,rotation=rot,color=tc)
    ax.update_datalim([(x,y),(x+w*math.cos(a)-h*math.sin(a),y+w*math.sin(a)+h*math.cos(a)),(x+w*math.cos(a),y+w*math.sin(a)),(x-h*math.sin(a),y+h*math.cos(a))])
def tube(ax,p,q,c): ax.plot([p[0],q[0]],[p[1],q[1]],ls="--",color=c,lw=2)
